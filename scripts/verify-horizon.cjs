const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..'),source=fs.readFileSync(path.join(root,'src/app.js'),'utf8');
const ctx=vm.createContext({data:JSON.parse(fs.readFileSync(path.join(root,'data/catalogue.json'),'utf8')).actions,selected:new Set(),scenario:{income:2,corporate:3,dividends:'vm'},units:{},conditions:{yle:'reduce-tax',farm:'redirect'},year:2031,includeLater:false});
vm.runInContext('const baseData=new Map(data.map(d=>[d.id,{...d}]));data.forEach(d=>{if(d.unit)units[d.id]=1;});',ctx);
vm.runInContext(source.slice(source.indexOf('  function syncScenario(){'),source.indexOf('  const esc=')),ctx);
const refresh=later=>{ctx.includeLater=later;ctx.syncScenario();};
const get=id=>ctx.data.find(d=>d.id===id);
refresh(false);
const baseline=Object.fromEntries(ctx.data.map(d=>[d.id,d.amount]));
assert.equal(get('cut-2-51').amount,0);
assert.equal(get('cut-2-51').horizonEstimate.amount,110);
assert.equal(get('cut-2-51').horizonEstimate.when,'2033');
refresh(true);
assert.equal(get('cut-2-51').amount,110);
assert.equal(get('cut-7-20').amount,100);
assert.equal(get('cut-7-20').horizonEstimate.when,'2035');
assert.equal(get('cut-3-52').amount,baseline['cut-3-52']);
assert.match(get('cut-3-52').horizonEstimate.when,/2060/);
assert.equal(get('cut-3-45').amount,baseline['cut-3-45']);
assert.equal(get('cut-3-45').laterApplied,false);
assert.equal(get('cut-2-51').incidenceHorizonGap,false);
for(const id of ['cut-1-42','cut-1-72'])assert.equal(get(id).amount,0,'funding choices must still apply');
assert.equal(get('cut-3-62').amount,null,'do not turn unknown net into a direct estimate');
assert.equal(get('vat').amount,baseline.vat,'preserve reviewed tax net');
const laterAmounts=Object.fromEntries(ctx.data.map(d=>[d.id,d.amount]));
refresh(true);assert.deepEqual(Object.fromEntries(ctx.data.map(d=>[d.id,d.amount])),laterAmounts,'re-render cannot compound values');
refresh(false);assert.deepEqual(Object.fromEntries(ctx.data.map(d=>[d.id,d.amount])),baseline,'switching back restores all 243 annual amounts');
assert.ok(ctx.data.every(d=>!d.laterApplied&&!d.incidenceHorizonGap));
console.log('PASS: 2031 and later annual estimates, source dates, conditional funding, unknown nets and complete reversible switching.');
